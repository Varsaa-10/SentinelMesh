#!/usr/bin/env bash
# lab_env.sh — shared shell loader for active SentinelMesh environment profile.
# Sources root .env when present, otherwise defaults to env/E1.env.

_LAB_ENV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
_LAB_ENV_ROOT="$(cd "$_LAB_ENV_DIR/.." && pwd)"

_SM_SELECTED_ENV="${SM_ENV_FILE:-}"
if [ -z "$_SM_SELECTED_ENV" ]; then
    if [ -f "$_LAB_ENV_ROOT/.env" ]; then
        _SM_SELECTED_ENV="$_LAB_ENV_ROOT/.env"
    elif [ -f "$_LAB_ENV_ROOT/env/E1.env" ]; then
        _SM_SELECTED_ENV="$_LAB_ENV_ROOT/env/E1.env"
    fi
fi

# Preserve any caller-provided URL overrides across profile sourcing
_CALLER_WEBAPP_URL="${WEBAPP_URL:-}"
_CALLER_AUTHSERVICE_URL="${AUTHSERVICE_URL:-}"
_CALLER_GRAFANA_URL="${GRAFANA_URL:-}"

if [ -n "$_SM_SELECTED_ENV" ] && [ -f "$_SM_SELECTED_ENV" ]; then
    set -a
    # shellcheck disable=SC1090
    . "$_SM_SELECTED_ENV"
    set +a
fi

ENV_ID="${ENV_ID:-E1}"
CONTAINER_PREFIX="${CONTAINER_PREFIX:-sentinelmesh}"
COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-$CONTAINER_PREFIX}"
LAB_NET_NAME="${LAB_NET_NAME:-${CONTAINER_PREFIX}_net}"

WEBAPP_CONTAINER="${WEBAPP_CONTAINER:-${CONTAINER_PREFIX}-webapp}"
AUTHSERVICE_CONTAINER="${AUTHSERVICE_CONTAINER:-${CONTAINER_PREFIX}-authservice}"
DATABASE_CONTAINER="${DATABASE_CONTAINER:-${CONTAINER_PREFIX}-database}"
LOGCOLLECTOR_CONTAINER="${LOGCOLLECTOR_CONTAINER:-${CONTAINER_PREFIX}-logcollector}"
DASHBOARD_CONTAINER="${DASHBOARD_CONTAINER:-${CONTAINER_PREFIX}-dashboard}"
PROXY_CONTAINER="${PROXY_CONTAINER:-${CONTAINER_PREFIX}-proxy}"
NGROK_CONTAINER="${NGROK_CONTAINER:-${CONTAINER_PREFIX}-ngrok}"
DEBUG_CONTAINER="${DEBUG_CONTAINER:-${CONTAINER_PREFIX}-debug}"

WEBAPP_PORT="${WEBAPP_PORT:-5000}"
AUTHSERVICE_PORT="${AUTHSERVICE_PORT:-5001}"
POSTGRES_PORT="${POSTGRES_PORT:-5432}"
GRAFANA_PORT="${GRAFANA_PORT:-3000}"
FLUENTD_PORT="${FLUENTD_PORT:-24224}"

LOG_DIR="${LOG_DIR:-/var/log/sentinelmesh}"

DB_NAME="${DB_NAME:-sentinelmesh}"
DB_USER="${DB_USER:-postgres}"
DB_PASS="${DB_PASS:-postgres}"
JWT_SECRET="${JWT_SECRET:-sentinelmesh-secret-key}"
TEST_USER="${TEST_USER:-testuser}"
TEST_PASS="${TEST_PASS:-testpass}"

AUTH_DEFAULT_USER="${AUTH_DEFAULT_USER:-admin}"
AUTH_DEFAULT_PASS="${AUTH_DEFAULT_PASS:-admin123}"
GRAFANA_ADMIN_USER="${GRAFANA_ADMIN_USER:-admin}"
GRAFANA_ADMIN_PASS="${GRAFANA_ADMIN_PASS:-admin}"

if [ -n "$_CALLER_WEBAPP_URL" ]; then
    WEBAPP_URL="$_CALLER_WEBAPP_URL"
else
    WEBAPP_URL="http://127.0.0.1:${WEBAPP_PORT}"
fi
if [ -n "$_CALLER_AUTHSERVICE_URL" ]; then
    AUTHSERVICE_URL="$_CALLER_AUTHSERVICE_URL"
else
    AUTHSERVICE_URL="http://127.0.0.1:${AUTHSERVICE_PORT}"
fi
if [ -n "$_CALLER_GRAFANA_URL" ]; then
    GRAFANA_URL="$_CALLER_GRAFANA_URL"
else
    GRAFANA_URL="http://127.0.0.1:${GRAFANA_PORT}"
fi

export ENV_ID COMPOSE_PROJECT_NAME CONTAINER_PREFIX LAB_NET_NAME \
    WEBAPP_CONTAINER AUTHSERVICE_CONTAINER DATABASE_CONTAINER \
    LOGCOLLECTOR_CONTAINER DASHBOARD_CONTAINER PROXY_CONTAINER \
    NGROK_CONTAINER DEBUG_CONTAINER \
    WEBAPP_PORT AUTHSERVICE_PORT POSTGRES_PORT GRAFANA_PORT FLUENTD_PORT \
    LOG_DIR DB_NAME DB_USER DB_PASS JWT_SECRET TEST_USER TEST_PASS \
    AUTH_DEFAULT_USER AUTH_DEFAULT_PASS GRAFANA_ADMIN_USER GRAFANA_ADMIN_PASS \
    WEBAPP_URL AUTHSERVICE_URL GRAFANA_URL
