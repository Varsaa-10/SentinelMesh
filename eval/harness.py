
#!/usr/bin/env python3
"""
harness.py — SentinelMesh Module A3 logging harness + Baseline 1 runner.

Runs:
    1. Falco via falco_shim.py
    2. log-tail tailer.py
    3. S7 Grafana detector (optional)
    4. attack scripts (optional)

The harness captures all detector output into a timestamped run folder,
merges alerts into alerts.jsonl, scores them against ground_truth.json,
and writes baseline1_results.json.

S7 Grafana detector:
    scenario7_grafana_detector.py

The S7 detector watches:
    docker logs -f <grafana-container>

and emits JSON alerts for:
    - Successful Grafana login
    - Anonymous dashboard/API access
"""

import argparse
import json
import os
import signal
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path


# ---------------------------------------------------------------------------
# Attack order
# ---------------------------------------------------------------------------

# All single-technique scenarios.
#
# S7 is now included because the Grafana attack script has been built.
#
# S10 is the chained scenario and is intentionally NOT included here by
# default. It is appended separately when --chain-script is supplied.
DEFAULT_ATTACK_ORDER = [
    ("S1", "scenario1_sqli.sh", "bash"),
    ("S2", "scenario2_bruteforce.sh", "bash"),
    ("S3", "scenario3_default_credentials.sh", "bash"),
    ("S4", "scenario4_jwt_confusion.py", "python3"),
    ("S5", "scenario5_db_connection.sh", "bash"),
    ("S6", "scenario6_log_tampering.sh", "bash"),

    # S7 — Grafana default credentials + anonymous access
    ("S7", "scenario7_grafana_default_creds.sh", "bash"),

    # Existing credential-access scenario
    ("S9", "scenario9_credential_access.sh", "bash"),

    ("S8", "scenario8_exfiltration.sh", "bash"),
]


SECONDS_BETWEEN_ATTACKS = 4


# ---------------------------------------------------------------------------
# Utility
# ---------------------------------------------------------------------------

def now_ts():
    return datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")


def log(msg):
    print(f"[harness] {msg}", file=sys.stderr, flush=True)


# ---------------------------------------------------------------------------
# Falco
# ---------------------------------------------------------------------------

def start_falco(rules_dir, shim_path, out_path, stderr_dir):
    rules_dir = Path(rules_dir)

    rule_files = sorted(rules_dir.glob("s0*.yaml"))

    if not rule_files:
        log(f"WARNING: no s0*.yaml rule files found in {rules_dir}")

    falco_cmd = [
        "stdbuf",
        "-oL",
        "falco",
        "-o",
        "json_output=true",
    ]

    for rf in rule_files:
        falco_cmd += ["-r", str(rf)]

    log(
        f"starting falco: {' '.join(falco_cmd)} | {shim_path}"
    )

    out_f = open(out_path, "w")
    falco_err_f = open(
        stderr_dir / "falco_stderr.log",
        "w",
    )
    shim_err_f = open(
        stderr_dir / "shim_stderr.log",
        "w",
    )

    falco_proc = subprocess.Popen(
        falco_cmd,
        stdout=subprocess.PIPE,
        stderr=falco_err_f,
    )

    shim_proc = subprocess.Popen(
        [sys.executable, str(shim_path)],
        stdin=falco_proc.stdout,
        stdout=out_f,
        stderr=shim_err_f,
    )

    falco_proc.stdout.close()

    return (
        falco_proc,
        shim_proc,
        out_f,
        falco_err_f,
        shim_err_f,
    )


# ---------------------------------------------------------------------------
# Log tailer
# ---------------------------------------------------------------------------

def start_tailer(
    tailer_path,
    webapp_log,
    auth_log,
    out_path,
    stderr_dir,
):
    cmd = [
        sys.executable,
        str(tailer_path),
        "--files",
        f"webapp={webapp_log}",
        f"authservice={auth_log}",
    ]

    log(f"starting tailer: {' '.join(cmd)}")

    out_f = open(out_path, "w")
    err_f = open(
        stderr_dir / "tailer_stderr.log",
        "w",
    )

    proc = subprocess.Popen(
        cmd,
        stdout=out_f,
        stderr=err_f,
    )

    return proc, out_f, err_f


# ---------------------------------------------------------------------------
# S7 Grafana detector
# ---------------------------------------------------------------------------

def start_grafana_detector(
    detector_path,
    container_name,
    out_path,
    stderr_dir,
):
    """
    Start the S7 Grafana detector.

    The detector itself follows:
        docker logs -f <container>

    Its stdout is expected to contain JSON alert lines generated by
    emit_alert().
    """

    cmd = [
        sys.executable,
        str(detector_path),
        "--container",
        container_name,
    ]

    log(
        f"starting Grafana detector: {' '.join(cmd)}"
    )

    out_f = open(out_path, "w")

    err_f = open(
        stderr_dir / "grafana_detector_stderr.log",
        "w",
    )

    proc = subprocess.Popen(
        cmd,
        stdout=out_f,
        stderr=err_f,
    )

    return proc, out_f, err_f


# ---------------------------------------------------------------------------
# Attack scripts
# ---------------------------------------------------------------------------

def run_attack_scripts(
    attack_scripts_dir,
    chain_script=None,
):
    attack_scripts_dir = Path(attack_scripts_dir)

    order = list(DEFAULT_ATTACK_ORDER)

    if chain_script:
        order.append(
            ("S10", chain_script, "bash")
        )

    chain_window = None

    for scenario, filename, interpreter in order:
        script_path = (attack_scripts_dir / filename).resolve()

        if scenario == "S10" and script_path.exists():
            chain_window = {
                "start": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                "end": None,
            }

        if not script_path.exists():
            log(
                f"SKIPPING {scenario}: "
                f"{script_path} not found"
            )
            continue

        log(
            f"firing {scenario}: {filename}"
        )

        try:
            result = subprocess.run(
                [interpreter, str(script_path)],
                timeout=30,
                capture_output=True,
                text=True,
            )

            if result.stdout:
                log(
                    f"{scenario} stdout:\n"
                    f"{result.stdout.strip()}"
                )

            if result.stderr:
                log(
                    f"{scenario} stderr:\n"
                    f"{result.stderr.strip()}"
                )

        except subprocess.TimeoutExpired:
            log(
                f"WARNING: {filename} timed out "
                f"after 30s, continuing"
            )

        except Exception as exc:
            log(
                f"WARNING: {filename} raised {exc}, "
                f"continuing"
            )

        time.sleep(SECONDS_BETWEEN_ATTACKS)

        if scenario == "S10" and chain_window is not None:
            chain_window["end"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    return chain_window


# ---------------------------------------------------------------------------
# Chain tagging
# ---------------------------------------------------------------------------

CHAIN_STAGES = ["S1", "S3", "S4", "S9", "S8"]  # eval/ground_truth.json S10.expected_alerts_in_order


def tag_chain_alerts(alerts, chain_window, stages=CHAIN_STAGES, chain_id="S10"):
    """Mark alerts produced by the chain script.

    Alerts keep their component `scenario` (S1, S3, ...) so per-scenario
    scoring is unchanged. Alerts whose timestamp falls inside the window in
    which the chain script ran, and whose scenario is a chain stage, also get
    chain_id="S10" and component_scenario=<scenario>. That is what lets the
    graph reconstruct a path for S10 itself.
    """
    if not chain_window or not chain_window.get("start"):
        return 0
    start = chain_window["start"]
    end = chain_window.get("end") or "9999-12-31T23:59:59Z"
    n = 0
    for a in alerts:
        ts = a.get("timestamp", "")
        if start <= ts <= end and a.get("scenario") in stages:
            a["chain_id"] = chain_id
            a["component_scenario"] = a["scenario"]
            n += 1
    return n


# ---------------------------------------------------------------------------
# Merge alerts
# ---------------------------------------------------------------------------

def merge_alerts(
    falco_out_path,
    tailer_out_path,
    merged_path,
    grafana_out_path=None,
    chain_window=None,
):
    """
    Merge all detector JSONL output into one timestamp-sorted file.

    Falco/shim:
        falco_alerts_raw.jsonl

    Log tailer:
        logtail_alerts_raw.jsonl

    S7 Grafana detector:
        grafana_alerts_raw.jsonl
    """

    alerts = []

    paths = [
        falco_out_path,
        tailer_out_path,
    ]

    if grafana_out_path is not None:
        paths.append(grafana_out_path)

    for path in paths:
        if not os.path.exists(path):
            continue

        with open(path) as f:
            for line in f:
                line = line.strip()

                if not line:
                    continue

                try:
                    alerts.append(
                        json.loads(line)
                    )
                except json.JSONDecodeError:
                    continue

    alerts.sort(
        key=lambda a: a.get(
            "timestamp",
            "",
        )
    )

    tagged = tag_chain_alerts(alerts, chain_window)
    if chain_window:
        log(f"tagged {tagged} alerts as S10 chain stages (window {chain_window})")

    with open(merged_path, "w") as f:
        for alert in alerts:
            f.write(
                json.dumps(alert) + "\n"
            )

    return alerts


# ---------------------------------------------------------------------------
# Ground-truth scoring
# ---------------------------------------------------------------------------

def score_against_ground_truth(
    alerts,
    ground_truth,
):
    """
    For each scenario in ground_truth (excluding S10),
    check whether at least one alert matches:

        expected_scenario
        expected_title
        expected_severity

    S10 is scored separately because it is a multi-alert chain.
    """

    results = {}

    scenarios = ground_truth["scenarios"]

    for sid, spec in scenarios.items():

        if sid == "S10":
            continue

        detection = spec.get(
            "detection",
            {},
        )

        expected_scenario = detection.get(
            "expected_scenario"
        )

        expected_title = detection.get(
            "expected_title"
        )

        expected_severity = detection.get(
            "expected_severity"
        )

        matches = [
            alert
            for alert in alerts
            if (
                alert.get("scenario")
                == expected_scenario
                and str(
                    alert.get("title", "")
                ).startswith(
                    expected_title or ""
                )
                and alert.get("severity")
                == expected_severity
            )
        ]

        results[sid] = {
            "name": spec.get("name"),
            "expected_scenario": expected_scenario,
            "expected_title": expected_title,
            "expected_severity": expected_severity,
            "fired": len(matches) > 0,
            "match_count": len(matches),
            "matched_alerts": matches,
        }

    # -----------------------------------------------------------------------
    # S10 chain scoring
    # -----------------------------------------------------------------------

    if "S10" in scenarios:

        s10 = scenarios["S10"]

        expected_stages = (
            s10
            .get("detection", {})
            .get(
                "expected_alerts_in_order",
                [],
            )
        )

        stage_results = {}

        for stage in expected_stages:

            stage_spec = (
                scenarios
                .get(stage, {})
                .get("detection", {})
            )

            matches = [
                alert
                for alert in alerts
                if (
                    alert.get("scenario")
                    == stage_spec.get(
                        "expected_scenario"
                    )
                    and str(
                        alert.get("title", "")
                    ).startswith(
                        stage_spec.get(
                            "expected_title"
                        ) or ""
                    )
                )
            ]

            stage_results[stage] = (
                len(matches) > 0
            )

        results["S10"] = {
            "name": s10.get("name"),
            "expected_stages": expected_stages,
            "stage_fired": stage_results,
            "all_stages_fired": (
                all(stage_results.values())
                if stage_results
                else False
            ),
        }

    return results


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():

    ap = argparse.ArgumentParser(
        description=(
            "SentinelMesh Module A3 logging harness / "
            "Baseline 1 runner"
        )
    )

    # Required core arguments
    ap.add_argument(
        "--ground-truth",
        required=True,
    )

    ap.add_argument(
        "--falco-rules-dir",
        required=True,
    )

    ap.add_argument(
        "--falco-shim",
        required=True,
    )

    ap.add_argument(
        "--tailer",
        required=True,
    )

    ap.add_argument(
        "--webapp-log",
        required=True,
    )

    ap.add_argument(
        "--auth-log",
        required=True,
    )

    # Attack configuration
    ap.add_argument(
        "--attack-scripts-dir",
        default=None,
    )

    ap.add_argument(
        "--auto-run-attacks",
        action="store_true",
        help=(
            "Automatically fire all single-technique "
            "attack scripts in order"
        ),
    )

    ap.add_argument(
        "--chain-script",
        default=None,
        help=(
            "Filename of the S10 chain script "
            "(e.g. scenario9_chain.sh)"
        ),
    )

    # S7 Grafana detector
    ap.add_argument(
        "--grafana-detector",
        default=None,
        help=(
            "Path to the S7 Grafana detector script "
            "(e.g. scenario7_grafana_detector.py)"
        ),
    )

    ap.add_argument(
        "--grafana-container",
        default="sentinelmesh-dashboard",
        help=(
            "Grafana Docker container name used by "
            "the S7 detector"
        ),
    )

    # Manual mode
    ap.add_argument(
        "--listen-seconds",
        type=int,
        default=120,
        help=(
            "If not --auto-run-attacks, how long to "
            "listen for manually-fired attacks"
        ),
    )

    # Output
    ap.add_argument(
        "--run-dir",
        default="runs",
        help=(
            "Base directory for timestamped run folders"
        ),
    )

    args = ap.parse_args()

    # -----------------------------------------------------------------------
    # Ground truth
    # -----------------------------------------------------------------------

    with open(args.ground_truth) as f:
        ground_truth = json.load(f)

    # -----------------------------------------------------------------------
    # Run directory
    # -----------------------------------------------------------------------

    run_id = now_ts()

    run_path = (
        Path(args.run_dir)
        / run_id
    )

    run_path.mkdir(
        parents=True,
        exist_ok=True,
    )

    log(
        f"run folder: "
        f"{run_path.resolve()}"
    )

    # -----------------------------------------------------------------------
    # Output files
    # -----------------------------------------------------------------------

    falco_out = (
        run_path
        / "falco_alerts_raw.jsonl"
    )

    tailer_out = (
        run_path
        / "logtail_alerts_raw.jsonl"
    )

    grafana_out = (
        run_path
        / "grafana_alerts_raw.jsonl"
    )

    # -----------------------------------------------------------------------
    # Process handles
    # -----------------------------------------------------------------------

    falco_proc = None
    shim_proc = None
    falco_f = None
    falco_err_f = None
    shim_err_f = None

    tailer_proc = None
    tailer_f = None
    tailer_err_f = None

    grafana_proc = None
    grafana_f = None
    grafana_err_f = None

    # -----------------------------------------------------------------------
    # Start Falco
    # -----------------------------------------------------------------------

    (
        falco_proc,
        shim_proc,
        falco_f,
        falco_err_f,
        shim_err_f,
    ) = start_falco(
        args.falco_rules_dir,
        args.falco_shim,
        falco_out,
        run_path,
    )

    # -----------------------------------------------------------------------
    # Start log tailer
    # -----------------------------------------------------------------------

    (
        tailer_proc,
        tailer_f,
        tailer_err_f,
    ) = start_tailer(
        args.tailer,
        args.webapp_log,
        args.auth_log,
        tailer_out,
        run_path,
    )

    # -----------------------------------------------------------------------
    # Start S7 Grafana detector
    # -----------------------------------------------------------------------

    if args.grafana_detector:

        detector_path = Path(
            args.grafana_detector
        )

        if not detector_path.exists():
            log(
                "WARNING: Grafana detector does not "
                f"exist: {detector_path}"
            )
        else:
            (
                grafana_proc,
                grafana_f,
                grafana_err_f,
            ) = start_grafana_detector(
                detector_path,
                args.grafana_container,
                grafana_out,
                run_path,
            )

    # -----------------------------------------------------------------------
    # Wait for Falco readiness
    # -----------------------------------------------------------------------

    # Give both processes a moment to finish loading
    # rules / opening files.

    falco_err_path = (
        run_path
        / "falco_stderr.log"
    )

    max_wait = 120
    poll_interval = 2

    ready_markers = (
        "Loaded event sources",
        "Enabled event sources",
        "Starting internal webserver",
    )

    log(
        "waiting up to "
        f"{max_wait}s for falco to finish "
        "attaching its probe..."
    )

    waited = 0
    falco_ready = False

    while waited < max_wait:

        time.sleep(poll_interval)
        waited += poll_interval

        try:
            content = (
                falco_err_path
                .read_text()
            )

        except FileNotFoundError:
            continue

        if any(
            marker in content
            for marker in ready_markers
        ):

            falco_ready = True

            # Give it a few extra seconds after
            # the marker to ensure the probe is live.

            time.sleep(5)

            break

    if falco_ready:

        log(
            f"falco appears ready after "
            f"~{waited}s"
        )

    else:

        log(
            "WARNING: no readiness marker seen in "
            f"falco_stderr.log after {max_wait}s — "
            "proceeding anyway, but S5-S8 alerts "
            "may be missed. Check the stderr log manually."
        )

    log(
        "waiting 3s for tailer startup..."
    )

    time.sleep(3)

    # -----------------------------------------------------------------------
    # Run attacks / listen
    # -----------------------------------------------------------------------

    try:

        chain_window = None

        if args.auto_run_attacks:

            if not args.attack_scripts_dir:

                log(
                    "ERROR: --auto-run-attacks "
                    "requires --attack-scripts-dir"
                )

                sys.exit(1)

            chain_window = run_attack_scripts(
                args.attack_scripts_dir,
                chain_script=args.chain_script,
            )

            log(
                "all attack scripts fired. "
                "waiting 5s for final alerts to land..."
            )

            time.sleep(5)

        else:

            log(
                f"listening for "
                f"{args.listen_seconds}s — "
                "fire attack scripts manually "
                "in another terminal now"
            )

            time.sleep(
                args.listen_seconds
            )

    except KeyboardInterrupt:

        log(
            "interrupted, stopping early"
        )

    finally:

        # ---------------------------------------------------------------
        # Stop all detector processes
        # ---------------------------------------------------------------

        processes = [
            (
                "grafana detector",
                grafana_proc,
            ),
            (
                "tailer",
                tailer_proc,
            ),
            (
                "falco shim",
                shim_proc,
            ),
            (
                "falco",
                falco_proc,
            ),
        ]

        for name, proc in processes:

            if proc is None:
                continue

            try:

                log(
                    f"stopping {name}"
                )

                proc.send_signal(
                    signal.SIGTERM
                )

            except Exception:
                pass

        time.sleep(1)

        # ---------------------------------------------------------------
        # Force-kill anything still running
        # ---------------------------------------------------------------

        for name, proc in processes:

            if proc is None:
                continue

            try:

                if proc.poll() is None:
                    proc.kill()

            except Exception:
                pass

        # ---------------------------------------------------------------
        # Close output files
        # ---------------------------------------------------------------

        for f in (
            falco_f,
            tailer_f,
            grafana_f,
            falco_err_f,
            shim_err_f,
            tailer_err_f,
            grafana_err_f,
        ):

            if f is None:
                continue

            try:
                f.close()
            except Exception:
                pass

    # -----------------------------------------------------------------------
    # Merge alerts
    # -----------------------------------------------------------------------

    merged_path = (
        run_path
        / "alerts.jsonl"
    )

    alerts = merge_alerts(
        falco_out,
        tailer_out,
        merged_path,
        grafana_out_path=(
            grafana_out
            if args.grafana_detector
            else None
        ),
        chain_window=chain_window,
    )

    log(
        f"merged {len(alerts)} alerts -> "
        f"{merged_path}"
    )

    # -----------------------------------------------------------------------
    # Score
    # -----------------------------------------------------------------------

    results = score_against_ground_truth(
        alerts,
        ground_truth,
    )

    passed = sum(
        1
        for sid, result in results.items()
        if sid != "S10"
        and result.get("fired")
    )

    total_single = sum(
        1
        for sid in results
        if sid != "S10"
    )

    s10_pass = (
        results
        .get("S10", {})
        .get(
            "all_stages_fired",
            None,
        )
    )

    # -----------------------------------------------------------------------
    # Summary
    # -----------------------------------------------------------------------

    summary = {
        "run_id": run_id,
        "run_timestamp_utc": run_id,
        "baseline": (
            "Baseline 1 "
            "(Falco-only + log-tail + S7 Grafana detector, "
            "no RAG/graph/response)"
        ),
        "ground_truth_file": str(
            Path(
                args.ground_truth
            ).resolve()
        ),
        "grafana_detector": (
            str(
                Path(
                    args.grafana_detector
                ).resolve()
            )
            if args.grafana_detector
            else None
        ),
        "grafana_container": (
            args.grafana_container
            if args.grafana_detector
            else None
        ),
        "total_alerts_captured": len(
            alerts
        ),
        "single_scenario_pass_count": passed,
        "single_scenario_total": total_single,
        "s10_chain_all_stages_fired": s10_pass,
        "results": results,
    }

    # -----------------------------------------------------------------------
    # Write results
    # -----------------------------------------------------------------------

    results_path = (
        run_path
        / "baseline1_results.json"
    )

    with open(results_path, "w") as f:

        json.dump(
            summary,
            f,
            indent=2,
            default=str,
        )

    log(
        "Baseline 1 results written to: "
        f"{results_path.resolve()}"
    )

    log(
        f"Score: {passed}/{total_single} "
        "single-technique scenarios fired correctly"
    )

    if s10_pass is not None:

        log(
            "S10 chain: "
            + (
                "ALL STAGES FIRED"
                if s10_pass
                else "INCOMPLETE"
            )
        )

    if passed < total_single:

        log(
            "Some scenarios did not fire — "
            "check stderr logs for clues:"
        )

        log(
            f"  {run_path / 'falco_stderr.log'}"
        )

        log(
            f"  {run_path / 'shim_stderr.log'}"
        )

        log(
            f"  {run_path / 'tailer_stderr.log'}"
        )

        if args.grafana_detector:

            log(
                f"  {run_path / 'grafana_detector_stderr.log'}"
            )


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    main()


